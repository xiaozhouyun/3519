// --------------------------- 底层 SPI 接口与同步等待函数 ---------------------------

static inline void tft180_spi_wait_idle(void)
{
    while (!DL_SPI_isTXFIFOEmpty(TFT_SPI0_INST) || DL_SPI_isBusy(TFT_SPI0_INST));
}

static inline void tft180_write_8bit_data(uint8_t data)
{
    while (DL_SPI_isTXFIFOFull(TFT_SPI0_INST));
    DL_SPI_transmitData8(TFT_SPI0_INST, data);
}

static inline void tft180_write_16bit_data(uint16_t data)
{
    while (DL_SPI_isTXFIFOFull(TFT_SPI0_INST));
    DL_SPI_transmitData8(TFT_SPI0_INST, (uint8_t)(data >> 8));
    while (DL_SPI_isTXFIFOFull(TFT_SPI0_INST));
    DL_SPI_transmitData8(TFT_SPI0_INST, (uint8_t)(data & 0xFF));
}

static void tft180_write_index(const uint8_t dat)
{
    tft180_spi_wait_idle();
    TFT180_DC(0);
    DL_SPI_transmitData8(TFT_SPI0_INST, dat);
    tft180_spi_wait_idle();
    TFT180_DC(1);
}

static void tft180_set_region(uint16 x1, uint16 y1, uint16 x2, uint16 y2)
{
    zf_assert(x1 < tft180_x_max);
    zf_assert(y1 < tft180_y_max);
    zf_assert(x2 < tft180_x_max);
    zf_assert(y2 < tft180_y_max);

    switch(tft180_display_dir)
    {
        case TFT180_PORTAIT:
        case TFT180_PORTAIT_180:
        {
            tft180_write_index(0x2a);
            tft180_write_8bit_data(0x00);
            tft180_write_8bit_data(x1);
            tft180_write_8bit_data(0x00);
            tft180_write_8bit_data(x2);

            tft180_write_index(0x2b);
            tft180_write_8bit_data(0x00);
            tft180_write_8bit_data(y1);
            tft180_write_8bit_data(0x00);
            tft180_write_8bit_data(y2);
        }break;
        case TFT180_CROSSWISE:
        case TFT180_CROSSWISE_180:
        {
            tft180_write_index(0x2a);
            tft180_write_8bit_data(0x00);
            tft180_write_8bit_data(x1);
            tft180_write_8bit_data(0x00);
            tft180_write_8bit_data(x2);

            tft180_write_index(0x2b);
            tft180_write_8bit_data(0x00);
            tft180_write_8bit_data(y1);
            tft180_write_8bit_data(0x00);
            tft180_write_8bit_data(y2);
        }break;
    }
    tft180_write_index(0x2c);
}

// --------------------------- 单个 16x16 汉字渲染内部函数 (纵向取模) ---------------------------

static void tft180_draw_chinese_16x16(uint16 x, uint16 y, const uint8 bitmap[32], uint16 color)
{
    if (x >= tft180_x_max || y >= tft180_y_max || bitmap == NULL) return;

    TFT180_CS(0);
    tft180_set_region(x, y, x + 15, y + 15);
    
    // 适配用户 PC2LCD2002 纵向取模方式 (行扫描发送16列像素)
    for (int r = 0; r < 16; r++)
    {
        for (int c = 0; c < 16; c++)
        {
            uint8 byte_val = (r < 8) ? bitmap[c] : bitmap[c + 16];
            uint8 bit_shift = (r < 8) ? r : (r - 8);
            uint16 pixel_color = (byte_val & (1 << bit_shift)) ? color : tft180_bgcolor;
            tft180_write_16bit_data(pixel_color);
        }
    }
    
    tft180_spi_wait_idle();
    TFT180_CS(1);
}

