#ifndef ICM45686_H
#define ICM45686_H

/**
 * @file icm45686.h
 * @brief ICM45686 高性能六轴 IMU 传感器模块驱动头文件 (MSPM0G3519)
 * 
 * 硬件资源: SPI / I2C 通信总线
 * 具备功能:
 *   1. 六轴原始加速度与陀螺仪数据获取
 *   2. 设备 ID (WHO_AM_I) 校验自检
 *   3. 姿态解算 (Roll, Pitch, Yaw 姿态欧拉角计算与周期更新)
 */

#include "ti_msp_dl_config.h"
#include <stdint.h>
#include <fast_math.h>
/**
 * @brief ICM45686 芯片固定识别 ID 期望值 (WHO_AM_I 寄存器默认返回值 0xE9)
 */
#define ICM45686_WHO_AM_I_VALUE          (0xE9U)

/* ===================================================================================================================
 * 全局姿态与传感器原始数据导出变量
 * =================================================================================================================== */
extern int16_t icm45686_acc_x;  /**< 加速度计 X 轴原始数据 (带符号 16 位) */
extern int16_t icm45686_acc_y;  /**< 加速度计 Y 轴原始数据 (带符号 16 位) */
extern int16_t icm45686_acc_z;  /**< 加速度计 Z 轴原始数据 (带符号 16 位) */

extern int16_t icm45686_gyro_x; /**< 陀螺仪 X 轴原始数据 (带符号 16 位) */
extern int16_t icm45686_gyro_y; /**< 陀螺仪 Y 轴原始数据 (带符号 16 位) */
extern int16_t icm45686_gyro_z; /**< 陀螺仪 Z 轴原始数据 (带符号 16 位) */

extern float icm45686_roll;     /**< 实时解算横滚角 Roll (单位: 度 deg) */
extern float icm45686_pitch;    /**< 实时解算俯仰角 Pitch (单位: 度 deg) */
extern float icm45686_yaw;      /**< 实时解算偏航角 Yaw (单位: 度 deg) */

/* ===================================================================================================================
 * 驱动函数 API 接口声明
 * =================================================================================================================== */

/**
 * @brief  初始化 ICM45686 传感器硬件外设与内部寄存器配置
 * @return uint8_t 0: 初始化成功, 1: 初始化失败 (ID 不匹配或通讯超时)
 */
uint8_t icm45686_init(void);

/**
 * @brief  读取 ICM45686 设备的 WHO_AM_I 寄存器 ID 值
 * @return uint8_t 寄存器读取到的 ID 字节 (正常应为 0xE9)
 */
uint8_t icm45686_read_id(void);

/**
 * @brief  周期性姿态与传感器数据更新主接口
 * @param  dt 两次调用的时间间隔/控制周期 (单位: 秒 s，如 10ms 则传入 0.01f)
 */
void icm45686_update(float dt);

#endif /* ICM45686_H */
